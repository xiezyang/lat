.text
.global _start
.macro CHECK reg, lanes
    vmovdqu [rip + out], ymm\reg
    lea r8, [rip + out]
    mov r9, rdi
    mov ecx, \lanes
.Lcheck\@:
    mov eax, [r8]
    cmp eax, [r9]
    jne fail
    add r8, 4
    add r9, 4
    dec ecx
    jne .Lcheck\@
    .if \lanes == 4
      cmp qword ptr [rip + out + 16], 0
      jne fail
      cmp qword ptr [rip + out + 24], 0
      jne fail
    .endif
.endm
.macro SWEEP width, lanes
    lea rsi, [rip + input]
    lea rdi, [rip + expected]
    mov r10d, (input_end - input) / (\lanes * 4)
.Lloop\@:
    vmovdqu ymm0, [rsi]
    vroundps \width\()0, \width\()0, 0x0b
    CHECK 0,\lanes
    vmovdqu ymm0, [rsi]
    vroundps \width\()1, \width\()0, 0x0b
    CHECK 1,\lanes
    vpcmpeqd ymm1, ymm1, ymm1
    vroundps \width\()1, [rsi], 0x0b
    CHECK 1,\lanes
    add rsi, (\lanes * 4)
    add rdi, (\lanes * 4)
    dec r10d
    jne .Lloop\@
.endm
_start:
    SWEEP xmm,4
    SWEEP ymm,8
    xor edi, edi
    jmp exit
fail:
    mov edi, 1
exit:
    mov eax, 60
    syscall
